-- ADR-008: chat do atendimento online — sala = agendamento; só mensagens (append-only)
CREATE TABLE mensagem_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT NOT NULL REFERENCES agendamento(id),
    autor_id BIGINT NOT NULL REFERENCES usuario(id),
    conteudo VARCHAR(2000) NOT NULL,
    data_envio TIMESTAMP NOT NULL
);

CREATE INDEX idx_chat_agendamento ON mensagem_chat(agendamento_id, data_envio);

