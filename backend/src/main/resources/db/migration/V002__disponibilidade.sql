-- Fase 2: disponibilidade da agenda (UC06, RF08–RF16)
-- Nota: CHECK com CURRENT_DATE não é permitido no PostgreSQL (função não imutável) —
-- data passada é validada no serviço (DisponibilidadeService), como previsto no MODELO_DE_DADOS.
CREATE TABLE disponibilidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    duracao_minutos SMALLINT NOT NULL,
    modalidade VARCHAR(10) NOT NULL,           -- ONLINE | PRESENCIAL | HIBRIDO (RF10/11)
    local VARCHAR(255),                        -- presencial (#N7 — opcional até decisão)
    link_reuniao VARCHAR(500),                 -- online (#N6 — link informado pela coordenação)
    status VARCHAR(15) NOT NULL DEFAULT 'DISPONIVEL',  -- DISPONIVEL | BLOQUEADO | RESERVADO | EXPIRADO
    observacao VARCHAR(500),
    criado_por BIGINT NOT NULL REFERENCES usuario(id),
    data_criacao TIMESTAMP NOT NULL,
    CONSTRAINT ck_disponibilidade_horario CHECK (hora_fim > hora_inicio)
);

CREATE INDEX idx_disponibilidade_data_status ON disponibilidade(data, status);

