-- Fase 1: usuários, perfis, permissões e auditoria (MODELO_DE_DADOS.md)
CREATE TABLE perfil_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    descricao VARCHAR(255)
);

CREATE TABLE permissao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255)
);

CREATE TABLE perfil_permissao (
    perfil_id BIGINT NOT NULL REFERENCES perfil_acesso(id),
    permissao_id BIGINT NOT NULL REFERENCES permissao(id),
    PRIMARY KEY (perfil_id, permissao_id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    identificador_institucional VARCHAR(100) UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    perfil_id BIGINT NOT NULL REFERENCES perfil_acesso(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    data_cadastro TIMESTAMP NOT NULL,
    data_ultimo_acesso TIMESTAMP
);

CREATE TABLE aluno (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario(id),
    matricula VARCHAR(50) NOT NULL UNIQUE,
    curso VARCHAR(100) NOT NULL,
    periodo SMALLINT,
    turma VARCHAR(50),
    telefone VARCHAR(30),
    status_matricula VARCHAR(30) NOT NULL
);

CREATE TABLE coordenador (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario(id),
    registro_funcional VARCHAR(50) UNIQUE,
    cargo VARCHAR(100),
    area_responsabilidade VARCHAR(255)
);

CREATE TABLE administrador (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario(id),
    nivel_administrativo VARCHAR(30) NOT NULL
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    operacao VARCHAR(50) NOT NULL,
    entidade VARCHAR(50) NOT NULL,
    identificador_entidade BIGINT,
    data_hora TIMESTAMP NOT NULL,
    endereco_ip VARCHAR(64),
    detalhes VARCHAR(1000)
);

CREATE INDEX idx_auditoria_entidade ON auditoria(entidade, identificador_entidade);

