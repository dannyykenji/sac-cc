-- Fase 4: atendimento, histórico append-only e notificações (UC07–UC09, RF31–RF60, RN06–RN14)
CREATE TABLE atendimento (
    agendamento_id BIGINT PRIMARY KEY REFERENCES agendamento(id),   -- 1:1 (RN06)
    responsavel_id BIGINT NOT NULL REFERENCES usuario(id),          -- coordenador que registrou
    realizado BOOLEAN NOT NULL,
    data_realizacao TIMESTAMP NOT NULL,
    status_resolucao VARCHAR(15) NOT NULL,   -- RESOLVIDO | NAO_RESOLVIDO | EM_TRATATIVA
    observacoes VARCHAR(2000),               -- interno — jamais exposto ao aluno (RF43)
    solucao_registrada VARCHAR(2000),        -- obrigatório se RESOLVIDO (RN07)
    encaminhamento VARCHAR(500),             -- RF38
    prazo_retorno DATE,                      -- exigido se EM_TRATATIVA (RN08)
    data_encerramento TIMESTAMP
);

CREATE INDEX idx_atendimento_status ON atendimento(status_resolucao);
CREATE INDEX idx_atendimento_responsavel ON atendimento(responsavel_id);

CREATE TABLE historico_atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id BIGINT NOT NULL REFERENCES atendimento(agendamento_id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    status_anterior VARCHAR(15),
    status_novo VARCHAR(15) NOT NULL,
    descricao VARCHAR(2000),
    data_registro TIMESTAMP NOT NULL
);

CREATE INDEX idx_historico_atendimento ON historico_atendimento(atendimento_id);

CREATE TABLE notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id BIGINT NOT NULL REFERENCES usuario(id),
    agendamento_id BIGINT REFERENCES agendamento(id),
    tipo VARCHAR(40) NOT NULL,               -- CONFIRMACAO | LEMBRETE | CANCELAMENTO | ALTERACAO | STATUS
    canal VARCHAR(20) NOT NULL DEFAULT 'SISTEMA',
    assunto VARCHAR(255),
    mensagem VARCHAR(2000) NOT NULL,
    status_envio VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA',  -- MVP sem SMTP (#T5): só registra (RF56/60)
    data_criacao TIMESTAMP NOT NULL,
    data_envio TIMESTAMP,
    tentativas_envio SMALLINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_notificacao_destinatario ON notificacao(destinatario_id, data_criacao);
