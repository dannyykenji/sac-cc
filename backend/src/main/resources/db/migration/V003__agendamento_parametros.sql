CREATE TABLE agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(20) NOT NULL UNIQUE,             -- RN04
    aluno_id BIGINT NOT NULL REFERENCES usuario(id),
    disponibilidade_id BIGINT NOT NULL REFERENCES disponibilidade(id),
    categoria_id BIGINT REFERENCES categoria_atendimento(id),
    modalidade VARCHAR(10) NOT NULL,                   -- deve ser permitida pelo slot (RN15)
    assunto VARCHAR(255) NOT NULL,                     -- RF19
    descricao VARCHAR(2000),                           -- RF20
    status VARCHAR(20) NOT NULL DEFAULT 'SOLICITADO',
        -- SOLICITADO | CONFIRMADO | CANCELADO | REALIZADO | NAO_COMPARECEU | ENCERRADO
    -- espelho do slot no momento da criação (facilita queries futuras/histórico; atualizado na remarcação)
    data DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    data_criacao TIMESTAMP NOT NULL,
    data_cancelamento TIMESTAMP,
    motivo_cancelamento VARCHAR(500),
    cancelado_por BIGINT REFERENCES usuario(id)
);

CREATE INDEX idx_agendamento_aluno_status ON agendamento(aluno_id, status);
CREATE INDEX idx_agendamento_status ON agendamento(status);
CREATE INDEX idx_agendamento_disponibilidade ON agendamento(disponibilidade_id);
CREATE INDEX idx_agendamento_data ON agendamento(data);
